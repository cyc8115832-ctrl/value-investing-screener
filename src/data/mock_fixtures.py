    # 3. 寫入每檔股票的近期行情、營收與季報資料
    all_stocks = db.query(StockMaster).all()
    for s in all_stocks:
        t = s.ticker
        meta = STOCKS_METADATA.get(t, {"pe_min": 12.0, "pe_max": 25.0, "price": 100.0, "eps_est": 5.0})
        latest_p_in_db = db.query(PriceDaily).filter(PriceDaily.ticker == t, PriceDaily.date == today_dt).first()
        cur_price = latest_p_in_db.close if latest_p_in_db else meta.get("price", 100.0)
        target_eps = meta.get("eps_est", 5.0)

        # 估算合理流通股數 (百萬股) 與獲利規模
        shares_val = 25930.0 if t == "2330" else (1500.0 if cur_price < 500 else 300.0)
        annual_ni = target_eps * shares_val
        q_ni = annual_ni / 4.0
        net_marg = 0.38 if t == "2330" else 0.20
        q_rev = q_ni / net_marg
        base_rev = (q_rev * 4.0) / 12.0

        # 價格記錄 (回補半年前至今日之交易日歷史日線，包含 2026-04-06 基準日)
        # 定義 6 個月累計報酬走勢模型 (依據產業與基本面特性，包含獲利超額與景氣下行失敗樣本)
        if s.ticker in ["2330", "2454", "2382", "3231", "6669", "2379", "3034", "2357", "2377", "2385", "3017", "2474"]:
            gain_6m = 0.28
        elif s.ticker in ["2603", "2609", "2615"]:
            gain_6m = 0.24
        elif s.sector_type == "financial":
            gain_6m = 0.14
        elif s.ticker in ["1301", "1303", "1326", "2002", "1101"]:
            gain_6m = -0.05  # 景氣循環低迷與價值陷阱風險樣本 (依規格書 14.5 要求必須包含下跌失敗案例)
        elif s.ticker in ["1216", "2412", "3045", "4904", "2912"]:
            gain_6m = 0.04
        else:
            gain_6m = 0.12 if not s.is_cyclical else 0.06

        p_t0 = cur_price / (1.0 + gain_6m)
        total_days = 188  # 2026-04-01 至 2026-10-06
        for i in range(total_days + 1):
            d = today_dt - timedelta(days=i)
            if d.weekday() >= 5:  # 跳過週末
                continue
            existing_p = db.query(PriceDaily).filter(PriceDaily.ticker == t, PriceDaily.date == d).first()
            if not existing_p:
                progress = max(0.0, min(1.0, 1.0 - (i / 183.0)))
                wave = 1.0 + (0.015 * math.sin(i * 0.45 + (int(t) % 7)) if i > 0 else 0.0)
                day_close = round(p_t0 * (1.0 + gain_6m * progress) * wave, 2)
                vol = round(15000000.0 * (1.0 + 0.12 * math.cos(i * 0.3)), 0)
                p_record = PriceDaily(
                    ticker=t,
                    date=d,
                    close=day_close,
                    volume=vol,
                    pe=round(day_close / target_eps, 2),
                    pb=round(day_close / (cur_price * 0.4), 2),
                    ps=round(day_close / (cur_price * 0.8), 2)
                )
                db.add(p_record)

        # 月營收 (最近 12 個月)
        for m in range(1, 13):
            month_str = f"2026-{m:02d}" if m <= 9 else f"2025-{m:02d}"
            existing_rev = db.query(RevenueMonthly).filter(RevenueMonthly.ticker == t, RevenueMonthly.month == month_str).first()
            if not existing_rev:
                growth = 0.18 if not s.is_cyclical else 0.05
                rev = RevenueMonthly(
                    ticker=t,
                    month=month_str,
                    revenue=round(base_rev * (1.0 + m * 0.02), 2),
                    yoy=round(growth + (m % 3) * 0.02, 2),
                    cumulative_revenue=round(base_rev * m * 1.05, 2),
                    cumulative_yoy=round(growth, 2)
                )
                db.add(rev)

        # 季報 (最近 6 季，確保半年前回溯 T0 具有完整的 4 季 TTM 財報)
        for q_idx, q_name in enumerate(["2025-Q1", "2025-Q2", "2025-Q3", "2025-Q4", "2026-Q1", "2026-Q2"]):
            existing_q = db.query(FinancialsQuarterly).filter(FinancialsQuarterly.ticker == t, FinancialsQuarterly.quarter == q_name).first()
            if not existing_q:
                is_cyclical_low = t in ["1301", "1303", "1326", "2002", "1101"]
                gm_val = 0.09 if is_cyclical_low else (0.28 if s.is_cyclical else 0.52)
                om_val = 0.03 if is_cyclical_low else (0.12 if s.is_cyclical else 0.42)
                roe_val = 3.2 if is_cyclical_low else (9.5 if s.is_cyclical else 24.5)
                roic_val = 2.8 if is_cyclical_low else (8.0 if s.is_cyclical else 21.0)
                cf_mult = 0.10 if is_cyclical_low else 0.40

                fq = FinancialsQuarterly(
                    ticker=t,
                    quarter=q_name,
                    revenue=round(q_rev, 2),
                    gross_profit=round(q_rev * gm_val, 2),
                    operating_income=round(q_rev * om_val, 2),
                    net_income=round(q_ni, 2),
                    non_operating_income=round(q_rev * 0.02, 2),
                    gross_margin=gm_val,
                    operating_margin=om_val,
                    net_margin=round(net_marg, 2),
                    roe=roe_val,
                    roic=roic_val,
                    operating_cf=round(q_rev * cf_mult, 2),
                    capex=round(q_rev * 0.15, 2),
                    fcf=round(q_rev * 0.25, 2),
                    contract_liabilities=round(q_rev * 0.10, 2),
                    ppe=round(q_rev * 2.0, 2),
                    inventory=round(q_rev * 0.08, 2),
                    receivables=round(q_rev * 0.06, 2)
                )
                db.add(fq)

        # 流通股數
        existing_sh = db.query(SharesOutstanding).filter(SharesOutstanding.ticker == t, SharesOutstanding.date == today_dt).first()
        if not existing_sh:
            db.add(SharesOutstanding(ticker=t, date=today_dt, shares=shares_val))

        # 籌碼資料
        existing_chip = db.query(ChipData).filter(ChipData.ticker == t, ChipData.date == today_dt).first()
        if not existing_chip:
            db.add(ChipData(
                ticker=t,
                date=today_dt,
                foreign_net=3500.0,
                trust_net=1200.0,
                dealer_net=400.0,
                insider_holding_pct=28.5,
                big_holder_pct=76.2
            ))

    # 4. 填入心法庫
    for tip in MINDSET_TIPS_DATA:
        existing_tip = db.query(MindsetTip).filter(MindsetTip.text == tip["text"]).first()
        if not existing_tip:
            db.add(MindsetTip(category=tip["category"], text=tip["text"], active=True))

    # 5. 填入新手手冊 (A0 ~ A12 全套篇章)
    for art in MANUAL_ARTICLES_DATA:
        existing_art = db.query(ManualArticle).filter(ManualArticle.article_id == art["article_id"]).first()
        if not existing_art:
            db.add(ManualArticle(
                article_id=art["article_id"],
                chapter=art["chapter"],
                title=art["title"],
                body_md=art["body_md"],
                related_screen=art["related_screen"]
            ))
        else:
            existing_art.chapter = art["chapter"]
            existing_art.title = art["title"]
            existing_art.body_md = art["body_md"]
            existing_art.related_screen = art["related_screen"]

    # 6. 填入詞典 (26 項專有名詞白話辭典)
    for g in GLOSSARY_DATA:
        existing_g = db.query(GlossaryTerm).filter(GlossaryTerm.term_id == g["term_id"]).first()
        if not existing_g:
            db.add(GlossaryTerm(
                term_id=g["term_id"],
                term=g["term"],
                plain_explain=g["plain_explain"],
                example=g["example"]
            ))
        else:
            existing_g.term = g["term"]
            existing_g.plain_explain = g["plain_explain"]
            existing_g.example = g["example"]

    # 7. 初始化預設觀察清單群組 (規格書 7.1)
    default_groups = [
        {"id": "core_pool", "name": "核心候選", "order": 1, "type": "system"},
        {"id": "watch_cheap", "name": "便宜等催化", "order": 2, "type": "system"},
        {"id": "cyclical_tracking", "name": "循環轉折", "order": 3, "type": "system"},
        {"id": "warn_list", "name": "警戒待檢視", "order": 4, "type": "system"}
    ]
    for g in default_groups:
        existing_grp = db.query(WatchGroup).filter(WatchGroup.group_id == g["id"]).first()
        if not existing_grp:
            db.add(WatchGroup(group_id=g["id"], name=g["name"], sort_order=g["order"], group_type=g["type"]))

    db.commit()
    print("Database fixture seeding completed.")
